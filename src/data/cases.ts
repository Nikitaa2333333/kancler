/* mark — области подсветки поверх картинки, в % от ширины/высоты (маркер проходит по
   строке при прокрутке); result — крупный вывод под картинкой. Цифры — со слайдов. */
export interface Mark { x: number; y: number; w: number; h: number }
export interface CaseImage { src: string; alt: string; w: number; h: number; mark?: Mark[]; result?: string }
export interface Figure { value: string; label: string }
/* Живые графики (SVG/HTML) по цифрам со слайдов клиента. hi — индексы, которые
   подсвечиваем; ref — опорная линия (например, минимальный остаток). */
export type Chart =
  | { kind: 'area'; title: string; note?: string; unit: string; labels: string[]; values: number[]; ref?: { value: number; label: string }; hi?: number[] }
  | { kind: 'bars'; title: string; note?: string; unit: string; labels: string[]; values: number[]; hi?: number[] }
  | { kind: 'share'; title: string; note?: string; series: string[]; rows: { label: string; total: string; values: number[]; note?: string }[]; hi?: number }
  | { kind: 'stack'; title: string; note?: string; unit: string; total: { label: string; value: number }; parts: { label: string; value: number }[]; ref?: { value: number; label: string } };
export interface CaseSection { title: string; text?: string[]; list?: string[]; numbered?: boolean }
export interface Case {
  slug: string;
  title: string;
  short: string;   // одна строка-результат для карточки
  tags: string[];
  intro: string[];
  sections: CaseSection[];
  images: CaseImage[];
  service: { label: string; href: string };
  figures?: Figure[];
  charts?: Chart[];
}

