/* Русская типографика: висячие предлоги и союзы (1–2 буквы) приклеиваем к
   следующему слову неразрывным пробелом; тире отбиваем от предыдущего слова.
   Прогоняем ВСЕ тексты из src/data через typo() при выводе. */
const NBSP = ' ';
const SHORT = /(^|[\s(«"“—–-])([A-Za-zА-Яа-яЁё]{1,2})\s+(?=\S)/g;

export function typo(s: string): string {
  if (!s) return s;
  // два прохода: «и в», «у нас в» — после первой склейки второе слово ещё свободно
  let out = s.replace(SHORT, `$1$2${NBSP}`).replace(SHORT, `$1$2${NBSP}`);
  out = out.replace(/\s+—\s+/g, `${NBSP}— `);
  // разряды числа не разрываем: «40 320», «8 166 438»
  out = out.replace(/(\d) (?=\d{3}(?!\d))/g, `$1${NBSP}`);
  return out;
}
